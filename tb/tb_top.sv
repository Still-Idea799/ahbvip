`timescale 1ns/1ps

module tb_top;

    //=========================================================
    // Package Imports
    //=========================================================

    import uvm_pkg::*;
    import ahb_pkg::*;
    import test_pkg::*;

    `include "uvm_macros.svh"

    //=========================================================
    // Clock & Reset
    //=========================================================

    logic HCLK;
    logic HRESETn;

    //=========================================================
    // Interface Instance
    //=========================================================

    ahb_if ahb_vif(
        .HCLK    (HCLK),
        .HRESETn (HRESETn)
    );

    //=========================================================
    // Clock Generation
    //=========================================================

    initial begin

        HCLK = 1'b0;

        forever #5 HCLK = ~HCLK;

    end

    //=========================================================
    // Reset Generation
    //=========================================================

    initial begin

        HRESETn = 1'b0;

        repeat(5) @(posedge HCLK);

        HRESETn = 1'b1;

    end

    //=========================================================
    // UVM Configuration
    //=========================================================

    initial begin

        //---------------------------------------------
        // Virtual Interface
        //---------------------------------------------

        uvm_config_db #(virtual ahb_if)::set(
            null,
            "*",
            "vif",
            ahb_vif
        );

        //---------------------------------------------
        // Start Test
        //---------------------------------------------

        run_test();

    end

endmodule